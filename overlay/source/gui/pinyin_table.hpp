// ---- UTF-8 工具 ----

// 解出一个 UTF-8 字符的长度（1~4 字节）
inline size_t Utf8CharLen(unsigned char c) {
    if (c >= 0xF0) return 4;
    if (c >= 0xE0) return 3;
    if (c >= 0xC0) return 2;
    return 1;
}

// 从 p 处解出一个码点并前进 p
inline unsigned int Utf8NextCp(const char *&p) {
    if (!p || !*p) return 0;
    const unsigned char c0 = (unsigned char)p[0];
    size_t len = Utf8CharLen(c0);
    unsigned int cp = 0;
    if (len == 1) {
        cp = c0;
    } else if (len == 2) {
        cp = (unsigned int)(c0 & 0x1F) << 6;
        cp |= (unsigned int)((unsigned char)p[1] & 0x3F);
    } else if (len == 3) {
        cp = (unsigned int)(c0 & 0x0F) << 12;
        cp |= (unsigned int)((unsigned char)p[1] & 0x3F) << 6;
        cp |= (unsigned int)((unsigned char)p[2] & 0x3F);
    } else {
        cp = (unsigned int)(c0 & 0x07) << 18;
        cp |= (unsigned int)((unsigned char)p[1] & 0x3F) << 12;
        cp |= (unsigned int)((unsigned char)p[2] & 0x3F) << 6;
        cp |= (unsigned int)((unsigned char)p[3] & 0x3F);
    }
    p += len;
    return cp;
}

inline std::string NextUtf8Char(const char *&p) {
    if (!p || !*p) return "";
    const size_t len = Utf8CharLen((unsigned char)*p);
    std::string s(p, len);
    p += len;
    return s;
}

// 排序键：返回 'A'..'Z'（汉字按拼音首字母、英文按大写、数字/符号归 '0'，其它 '#'）
inline char GetInitial(const std::string &text) {
    if (text.empty()) return '#';
    const char *p = text.c_str();
    unsigned int cp = Utf8NextCp(p);
    if (cp == 0) return '#';

    if (cp >= 'a' && cp <= 'z') return (char)(cp - 'a' + 'A');
    if (cp >= 'A' && cp <= 'Z') return (char)cp;
    if (cp >= '0' && cp <= '9') return '0';

    // 汉字查表
    const size_t n = sizeof(g_char_initial) / sizeof(g_char_initial[0]);
    size_t lo = 0, hi = n;
    while (lo < hi) {
        const size_t mid = (lo + hi) / 2;
        if (g_char_initial[mid].cp < cp) lo = mid + 1;
        else hi = mid;
    }
    if (lo < n && g_char_initial[lo].cp == cp) return g_char_initial[lo].letter;
    return '#';
}

// 取候选词上限：8 页 × 8 条，供候选栏翻页
constexpr size_t kMaxCandidates = 64;

inline std::vector<std::string> GetCandidates(const std::string &py_input) {
    std::vector<std::string> res;
    if (py_input.empty()) return res;

    std::string py = py_input;
    for (auto &c : py) c = (char)std::tolower((unsigned char)c);

    auto push = [&](const std::string &s) {
        if (s.empty() || res.size() >= kMaxCandidates) return;
        if (std::find(res.begin(), res.end(), s) == res.end()) res.push_back(s);
    };


    // 2. 音节精确匹配（该音节的常用字）
    for (const auto &entry : g_table) {
        if (std::strcmp(entry.pinyin, py.c_str()) == 0) {
            const char *p = entry.chars;
            while (*p) push(NextUtf8Char(p));
            break;
        }
    }

    // 3. 前缀模糊匹配（补足候选，支持翻页）
    for (const auto &entry : g_table) {
        if (res.size() >= kMaxCandidates) break;
        if (std::strncmp(entry.pinyin, py.c_str(), py.size()) == 0) {
            const char *p = entry.chars;
            while (*p) {
                push(NextUtf8Char(p));
                if (res.size() >= kMaxCandidates) break;
            }
        }
    }

    return res;
}

